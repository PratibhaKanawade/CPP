#include<iostream>
using namespace std;
int main(){
    int a=5,b=3;
    //equal to equal to
    cout<<"a==b is:"<<(a==b)<<endl;
    //not equal to
    cout<<"a!=b is:"<<(a!=b)<<endl;
    //greater than
    cout<<"a>b is:"<<(a>b)<<endl;
    //less than
    cout<<"a<b is:"<<(a<b)<<endl;
    //greater than equal to
    cout<<"a>=b is:"<<(a>=b)<<endl;
    //less than equal to
    cout<<"a<=b is:"<<(a<=b)<<endl;
    return 0;

}           